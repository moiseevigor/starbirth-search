"""Write docs/RESEARCH_LOG.md from research/phases.py + computed results (same source as the viewer)."""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "research"))
sys.path.insert(0, str(ROOT / "src"))
from build_viewer import phases  # noqa: E402
from starbirth.glossary import markdown as glossary_md  # noqa: E402


def main() -> None:
    ph = phases()
    lines = ["# Research log", "",
             "One entry per phase, in order: question -> hypothesis -> test -> result -> verdict -> caveats -> next. "
             "Generated by `research/report_phases.py` from `research/phases.py`; the interactive version with "
             "figures and imagery is `viewer/index.html`, and the candidate review desk is `viewer/catalog.html` "
             "(see README).", "",
             "| id | phase | date | verdict |", "|---|---|---|---|"]
    lines += [f"| {p['id']} | {p['title']} | {p['date']} | **{p['verdict']}** |" for p in ph]
    for p in ph:
        lines += ["", f"## {p['id']} · {p['title']}", "", f"*{p['date']} · verdict: **{p['verdict']}***", "",
                  f"**Question.** {p['question']}", "", f"**Hypothesis / prediction.** {p['hypothesis']}", "",
                  f"**Test.** {p['test']}", "", f"**Result.** {p['result']}", "",
                  f"**What could still be wrong.** {p['caveats']}", "", f"**Next.** {p['next']}"]
    out = ROOT / "docs" / "RESEARCH_LOG.md"
    out.write_text("\n".join(lines) + "\n\n" + glossary_md())
    print(f"wrote {out} ({len(ph)} phases)")


if __name__ == "__main__":
    main()
